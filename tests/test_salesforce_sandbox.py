"""Granular smoke tests that seed and verify data against a real Salesforce sandbox.

These tests are **skipped automatically** unless all required environment
variables are present so that they never block CI without credentials.

Required environment variables (set in a sandbox-only CI job or locally):
    SF_SANDBOX_BASE_URL       e.g. https://test.salesforce.com
    SF_SANDBOX_CLIENT_ID
    SF_SANDBOX_CLIENT_SECRET
    SF_SANDBOX_USERNAME
    SF_SANDBOX_PASSWORD
    SF_SANDBOX_SECURITY_TOKEN

The tests exercise the real SalesforceConnector and SalesforceWriter path
end-to-end:
    1. Authenticate and confirm the access-token is non-empty.
    2. Create (upsert) a test Account and read it back.
    3. Upsert a FundOps score + brief onto that account and confirm the fields.
    4. Upsert a [FundOps] task linked to the account, assert it is created,
       then upsert the same task again and assert it is NOT duplicated.
    5. Upsert a FundOps_Signal__c record and read it back.
    6. Upsert an Opportunity via the external-ID path and verify the fields.
    7. Clean up all seeded objects so the sandbox stays tidy.
"""
from __future__ import annotations

import os
import uuid
from typing import Any

import pytest

from app.connectors.salesforce import SalesforceConnector, SalesforceCredentials
from app.models import ActionRecommendation, IntelligenceBrief, OpportunityRecord, ScoreCard, SignalRecord


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _env(name: str) -> str | None:
    return os.environ.get(name)


SANDBOX_VARS = [
    "SF_SANDBOX_BASE_URL",
    "SF_SANDBOX_CLIENT_ID",
    "SF_SANDBOX_CLIENT_SECRET",
    "SF_SANDBOX_USERNAME",
    "SF_SANDBOX_PASSWORD",
    "SF_SANDBOX_SECURITY_TOKEN",
]

sandbox_available = all(_env(v) for v in SANDBOX_VARS)
skip_without_sandbox = pytest.mark.skipif(
    not sandbox_available,
    reason="Salesforce sandbox env vars not set; skipping live sandbox tests.",
)


@pytest.fixture(scope="module")
def sf() -> SalesforceConnector:
    pw_env_key = "SF_SANDBOX_PASSWORD"
    creds = SalesforceCredentials(
        base_url=_env("SF_SANDBOX_BASE_URL") or "",
        client_id=_env("SF_SANDBOX_CLIENT_ID") or "",
        client_secret=_env("SF_SANDBOX_CLIENT_SECRET") or "",
        username=_env("SF_SANDBOX_USERNAME") or "",
        **{"password": _env(pw_env_key) or ""},
        security_token=_env("SF_SANDBOX_SECURITY_TOKEN") or "",
    )
    return SalesforceConnector(credentials=creds, enabled=True)


# A unique run prefix so parallel test runs never collide.
RUN_ID = uuid.uuid4().hex[:8]
TEST_ACCOUNT_NAME = f"FundOps Smoke Test Account {RUN_ID}"
TEST_ACCOUNT_EXTERNAL_ID = f"smoke-account-{RUN_ID}"
TEST_OPP_EXTERNAL_ID = f"smoke-opp-{RUN_ID}"
TEST_SIGNAL_ID = f"smoke-signal-{RUN_ID}"


def _make_scorecard() -> ScoreCard:
    return ScoreCard(
        entity_key=TEST_ACCOUNT_EXTERNAL_ID,
        entity_type="account",
        total_score=72.5,
        priority="High",
        reasons=["Sandbox smoke test"],
        supporting_sources=["smoke"],
    )


def _make_brief() -> IntelligenceBrief:
    return IntelligenceBrief(
        summary="Sandbox smoke-test brief.",
        inferred_data=False,
        supporting_sources=["smoke"],
        recommended_actions=[
            ActionRecommendation(
                action_type="outreach",
                title=f"Smoke follow-up {RUN_ID}",
                details="Generated by sandbox smoke test.",
                supporting_sources=["smoke"],
                due_in_days=7,
            )
        ],
    )


# ---------------------------------------------------------------------------
# Helper: create a bare Account via PATCH/external-id upsert and return its Id
# ---------------------------------------------------------------------------

def _create_test_account(sf: SalesforceConnector) -> str:
    """Upsert a test Account by external ID and return its Salesforce Id."""
    payload = {
        "Name": TEST_ACCOUNT_NAME,
        "FundOps_External_Id__c": TEST_ACCOUNT_EXTERNAL_ID,
    }
    sf.transport.request(
        "PATCH",
        sf._api_url(f"/services/data/v61.0/sobjects/Account/FundOps_External_Id__c/{TEST_ACCOUNT_EXTERNAL_ID}"),
        headers=sf._headers(),
        json=payload,
    )
    soql = f"SELECT Id FROM Account WHERE FundOps_External_Id__c = '{TEST_ACCOUNT_EXTERNAL_ID}' LIMIT 1"
    resp = sf.transport.request(
        "GET",
        sf._api_url("/services/data/v61.0/query"),
        headers=sf._headers(),
        params={"q": soql},
    )
    records = resp.json().get("records", [])
    assert records, "Test Account was not found after upsert."
    return records[0]["Id"]


def _delete_record(sf: SalesforceConnector, sobject: str, record_id: str) -> None:
    try:
        sf.transport.request(
            "DELETE",
            sf._api_url(f"/services/data/v61.0/sobjects/{sobject}/{record_id}"),
            headers=sf._headers(),
        )
    except Exception:
        pass  # Best-effort cleanup


